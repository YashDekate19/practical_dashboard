@app.route("/api/test-db", methods=["GET"])
def test_database():
    connection = get_db_connection()

    if connection is None:
        return jsonify({
            "success": False,
            "message": "Could not connect to Supabase PostgreSQL. Check DATABASE_URL in .env."
        }), 500

