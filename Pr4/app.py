# Allow frontend requests
CORS(app)

# ============================================================================
# SUPABASE POSTGRESQL DATABASE CONFIGURATION
# ============================================================================

DATABASE_URL = os.environ.get("DATABASE_URL")


def get_db_connection():
    """Establish connection to Supabase PostgreSQL database via DATABASE_URL"""
    if not DATABASE_URL or not DATABASE_URL.strip() or "your_supabase" in DATABASE_URL.lower():
        print("DATABASE_URL is not configured or contains placeholder.")
        return None

    try:
        connection = psycopg2.connect(DATABASE_URL, connect_timeout=5)
        # Ensure schema exists in case user has not manually executed SQL
        with connection.cursor() as cur:
            cur.execute("""
                CREATE TABLE IF NOT EXISTS users (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    name VARCHAR(100) NOT NULL,
                    email VARCHAR(255) NOT NULL UNIQUE,
                    password VARCHAR(255) NOT NULL,
                    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
                );
            """)
        connection.commit()
        return connection
    except Exception as e:
        print("Database connection error:", e)
        return None


