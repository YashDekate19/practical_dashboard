import os
import sqlite3
from pathlib import Path
import bcrypt
import psycopg2
from psycopg2.extras import RealDictCursor
from backend.config import Config


# -----------------------------------------------------------------------------
# Database Drivers & Connection Managers (Supabase PostgreSQL + SQLite Fallback)
# -----------------------------------------------------------------------------

def get_supabase_connection():
    """Attempt connecting to Supabase PostgreSQL using DATABASE_URL"""
    db_url = Config.DATABASE_URL or os.environ.get("DATABASE_URL")
    if not db_url or db_url.strip() == "" or "your_supabase" in db_url.lower():
        return None
    try:
        conn = psycopg2.connect(db_url, connect_timeout=5)
        # Ensure users table exists in the connected database
        with conn.cursor() as cur:
            cur.execute("""
                CREATE TABLE IF NOT EXISTS users (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    name VARCHAR(100) NOT NULL,
                    email VARCHAR(255) NOT NULL UNIQUE,
                    password VARCHAR(255) NOT NULL,
                    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
                );
            """)
        conn.commit()
        return conn
    except Exception:
        return None


def get_sqlite_connection():
    """Fallback SQLite database connection for seamless cloud/offline execution"""
    db_path = Path(Config.SQLITE_DB_PATH)
    db_path.parent.mkdir(parents=True, exist_ok=True)
    conn = sqlite3.connect(str(db_path), timeout=30.0)
    conn.row_factory = sqlite3.Row
    # Enable Write-Ahead Logging (WAL) and busy timeout to avoid database lock contention
    try:
        conn.execute("PRAGMA journal_mode=WAL;")
        conn.execute("PRAGMA busy_timeout=30000;")
    except Exception:
        pass

    # Ensure table exists
    with conn:
        conn.execute("""
            CREATE TABLE IF NOT EXISTS users (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                name TEXT NOT NULL,
                email TEXT NOT NULL UNIQUE,
                password TEXT NOT NULL,
                created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
            )
        """)
    return conn


def check_db_health():
    """Evaluate database status, prioritizing Supabase PostgreSQL, then SQLite fallback"""
    # 1. Supabase PostgreSQL
    pg_conn = get_supabase_connection()
    if pg_conn:
        try:
            with pg_conn.cursor() as cur:
                cur.execute("SELECT current_database(), count(*) FROM users")
                row = cur.fetchone()
                db_name = row[0]
                user_count = row[1]
            pg_conn.close()
            return {
                "ok": True,
                "type": "Supabase PostgreSQL",
                "database": db_name,
                "message": f"Connected to Supabase PostgreSQL [{db_name}] ({user_count} users registered)"
            }
        except Exception:
            if pg_conn:
                pg_conn.close()

    # 2. SQLite Fallback (used when DATABASE_URL is not yet configured)
    sqlite_conn = get_sqlite_connection()
    try:
        cursor = sqlite_conn.cursor()
        cursor.execute("SELECT count(*) FROM users")
        user_count = cursor.fetchone()[0]
        cursor.close()
        return {
            "ok": True,
            "type": "SQLite (Local Fallback)",
            "database": Path(Config.SQLITE_DB_PATH).name,
            "message": f"Active via SQLite fallback ({user_count} users registered). Configure DATABASE_URL for Supabase."
        }
    except Exception as e:
        return {
            "ok": False,
            "type": "None",
            "message": str(e)
        }
    finally:
        sqlite_conn.close()


