def find_user_by_email(email):
    """Retrieve user dictionary by email"""
    # 1. Supabase PostgreSQL
    pg_conn = get_supabase_connection()
    if pg_conn:
        try:
            with pg_conn.cursor(cursor_factory=RealDictCursor) as cur:
                cur.execute("SELECT id, name, email, password FROM users WHERE email = %s", (email,))
                user = cur.fetchone()
            pg_conn.close()
            return dict(user) if user else None
        except Exception:
            if pg_conn:
                pg_conn.close()

    # 2. SQLite Fallback
    sqlite_conn = get_sqlite_connection()
    try:
        cursor = sqlite_conn.cursor()
        cursor.execute("SELECT id, name, email, password FROM users WHERE email = ?", (email,))
        row = cursor.fetchone()
        user = dict(row) if row else None
        cursor.close()
        return user
    finally:
        sqlite_conn.close()


def insert_user(name, email, password_hash):
    """Insert newly registered user and return inserted user ID"""
    # 1. Supabase PostgreSQL
    pg_conn = get_supabase_connection()
    if pg_conn:
        try:
            with pg_conn.cursor() as cur:
                cur.execute(
                    "INSERT INTO users (name, email, password) VALUES (%s, %s, %s) RETURNING id",
                    (name, email, password_hash)
                )
                user_id = cur.fetchone()[0]
            pg_conn.commit()
            pg_conn.close()
            return user_id
        except Exception as e:
            if pg_conn:
                pg_conn.rollback()
                pg_conn.close()
            raise e

    # 2. SQLite Fallback
    sqlite_conn = get_sqlite_connection()
    try:
        cursor = sqlite_conn.cursor()
        cursor.execute(
            "INSERT INTO users (name, email, password) VALUES (?, ?, ?)",
            (name, email, password_hash)
        )
        sqlite_conn.commit()
        user_id = cursor.lastrowid
        cursor.close()
        return user_id
    finally:
        sqlite_conn.close()


def list_users():
    """Fetch all users sorted by id descending"""
    # 1. Supabase PostgreSQL
    pg_conn = get_supabase_connection()
    if pg_conn:
        try:
            with pg_conn.cursor(cursor_factory=RealDictCursor) as cur:
                cur.execute("SELECT id, name, email, created_at FROM users ORDER BY id DESC")
                users = [dict(row) for row in cur.fetchall()]
            pg_conn.close()
            return users
        except Exception:
            if pg_conn:
                pg_conn.close()

    # 2. SQLite Fallback
    sqlite_conn = get_sqlite_connection()
    try:
        cursor = sqlite_conn.cursor()
        cursor.execute("SELECT id, name, email, created_at FROM users ORDER BY id DESC")
        users = [dict(row) for row in cursor.fetchall()]
        cursor.close()
        return users
    finally:
        sqlite_conn.close()


