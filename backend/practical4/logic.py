def register_user(data):
    """Validate and register a new user with bcrypt password hashing"""
    if not data:
        return {"success": False, "message": "No data received"}, 400

    name = data.get("name", "").strip()
    email = data.get("email", "").strip().lower()
    password = data.get("password", "")

    if not name:
        return {"success": False, "message": "Name is required"}, 400
    if not email:
        return {"success": False, "message": "Email is required"}, 400
    if not password:
        return {"success": False, "message": "Password is required"}, 400
    if len(password) < 6:
        return {"success": False, "message": "Password must be at least 6 characters"}, 400

    # Check if user already exists
    existing = find_user_by_email(email)
    if existing:
        return {"success": False, "message": "Email is already registered"}, 409

    # Hash password with bcrypt
    password_hash = bcrypt.hashpw(
        password.encode("utf-8"),
        bcrypt.gensalt()
    ).decode("utf-8")

    try:
        user_id = insert_user(name, email, password_hash)
        return {
            "success": True,
            "message": "Registration successful",
            "user": {
                "id": user_id,
                "name": name,
                "email": email
            }
        }, 201
    except Exception as e:
        err_msg = str(e).lower()
        if "unique" in err_msg or "already exists" in err_msg or "duplicate" in err_msg:
            return {"success": False, "message": "Email is already registered"}, 409
        return {"success": False, "message": f"Registration failed: {str(e)}"}, 500


def authenticate_user(data):
    """Validate user credentials with bcrypt check"""
    if not data:
        return {"success": False, "message": "No data received"}, 400

    email = data.get("email", "").strip().lower()
    password = data.get("password", "")

    if not email or not password:
        return {"success": False, "message": "Email and password are required"}, 400

    user = find_user_by_email(email)
    if not user:
        return {"success": False, "message": "Invalid email or password"}, 401

    # Verify password hash
    try:
        password_valid = bcrypt.checkpw(
            password.encode("utf-8"),
            user["password"].encode("utf-8")
        )
    except Exception:
        password_valid = False

    if not password_valid:
        return {"success": False, "message": "Invalid email or password"}, 401

    return {
        "success": True,
        "message": "Login successful",
        "user": {
            "id": user["id"],
            "name": user["name"],
            "email": user["email"]
        }
    }, 200
